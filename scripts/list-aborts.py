#!/usr/bin/env python3
"""Lists every ENGINE_ASSERT / ENGINE_VERIFY / ENGINE_CHECK_SLOW site under engine/ and marks the ones a test is known to trigger.

Usage: scripts/list-aborts.py > KNOWN-ISSUES-untested-aborts.md

The COVERED table below is maintained by hand: add a (file, message prefix) entry when a test starts triggering a site
(through the throwing assert handler or a death test), then regenerate. A site that is not in the table is reported as untested.
"""
import glob, re, sys

# (file, text the site's message starts with) -> the test that triggers it
COVERED = {
    ('engine/foundation/containers/vector.h', 'Vector::Reserve'): 'tests/foundation/container_vector_test.cpp: Vector::Push asserts ... on allocator OOM',
    ('engine/foundation/containers/vector.h', 'Vector::Resize'): 'tests/foundation/container_vector_test.cpp: Vector::Resize asserts when the heap cannot supply the size',
    ('engine/foundation/containers/vector.h', 'Vector::Pop'): 'tests/foundation/container_vector_test.cpp: Vector::Pop asserts on an empty array',
    ('engine/rhi/device_host.cpp', 'DeviceHost::Recreate: called off'): 'tests/rhi/device_host_test.cpp: DeviceHost refuses Recreate inside a frame or off the owning thread',
    ('engine/rhi/device_host.cpp', 'DeviceHost::Recreate: called between'): 'tests/rhi/device_host_test.cpp: DeviceHost refuses Recreate inside a frame or off the owning thread',
    ('engine/rhi/device_host.cpp', 'DeviceHost::AddObserver'): 'tests/rhi/device_host_test.cpp: Adding or removing an observer during a reset is rejected',
    ('engine/rhi/device_host.cpp', 'DeviceHost::ReconfigureSwapchain: called between'): 'tests/rhi/swapchain_reconfigure_test.cpp: The host refuses to reconfigure inside a frame',
    ('engine/rhi/null/null_device.cpp', 'Swapchain::Reconfigure'): 'tests/rhi/swapchain_reconfigure_test.cpp: Reconfigure while an image is acquired is rejected',
    ('engine/foundation/debug/program_setup.cpp', '--crash-test=assert'): 'a deliberate assert behind the --crash-test flag, run by tests/debug (crash_end_to_end_linux_test)',
}

def sites():
    for f in sorted(glob.glob('engine/**/*.*', recursive=True)):
        if not f.endswith(('.h', '.cpp')) or 'generated' in f:
            continue
        lines = open(f, errors='ignore').read().split('\n')
        for i, l in enumerate(lines):
            if re.search(r'\bENGINE_(ASSERT|VERIFY|CHECK_SLOW)\(', l) and '#define' not in l:
                m = re.findall(r'"((?:[^"\\]|\\.)*)"', ' '.join(lines[i:i + 3]))
                yield f, i + 1, (m[0] if m else '')

rows = list(sites())
def covered(f, msg):
    for (cf, prefix), test in COVERED.items():
        if cf == f and msg.startswith(prefix):
            return test
    return None

untested = [(f, n, m) for f, n, m in rows if not covered(f, m)]
print('# Aborts with no test\n')
print('Every `ENGINE_ASSERT`, `ENGINE_VERIFY` and `ENGINE_CHECK_SLOW` under `engine/` (the `Aborts:` contracts) that no test is known to trigger. '
      'Generated by `scripts/list-aborts.py`; the table of covered sites is in that script. A test triggers one either through a death-test child '
      '(`engine/foundation/debug/death_test.h`) or through a throwing assert handler (`SetAssertHandler`, as `tests/foundation/container_vector_test.cpp` does).\n')
print(f'{len(rows)} sites, {len(rows) - len(untested)} covered, **{len(untested)} untested**.\n')
by_file = {}
for f, n, m in untested:
    by_file.setdefault(f, []).append((n, m))
for f in sorted(by_file):
    print(f'## `{f}` ({len(by_file[f])})\n')
    for n, m in by_file[f]:
        print(f'- line {n}: {m}')
    print()
print('## Covered\n')
for f, n, m in rows:
    t = covered(f, m)
    if t:
        print(f'- `{f}:{n}` {m[:70]} — {t}')
