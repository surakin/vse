#!/usr/bin/env python3
"""Generates engine/foundation/string/generated/grapheme_break_table.cpp from a
pinned Unicode version's GraphemeBreakProperty.txt and emoji-data.txt
(Extended_Pictographic lines only).

Dev-time only tool — never linked or shipped in the engine/game binary
(same category as CMake itself, PLAN.md assumption #8). Re-run by hand if
the pinned Unicode version ever changes; the generated output is checked
into the repo, not regenerated at build time.

Usage:
    python3 generate_grapheme_table.py \\
        <GraphemeBreakProperty.txt> <emoji-data.txt> \\
        <unicode-version> <output.cpp>
"""

import sys

# Unicode data file property name -> GraphemeBreakProperty enumerator name
# (engine/foundation/string/grapheme.h). "Other" is the @missing default and never
# appears as an explicit table entry.
GCB_PROPERTY_MAP = {
    "CR": "CR",
    "LF": "LF",
    "Control": "Control",
    "Extend": "Extend",
    "ZWJ": "ZWJ",
    "Regional_Indicator": "RegionalIndicator",
    "Prepend": "Prepend",
    "SpacingMark": "SpacingMark",
    "L": "L",
    "V": "V",
    "T": "T",
    "LV": "LV",
    "LVT": "LVT",
}

EMOJI_PROPERTY_MAP = {
    "Extended_Pictographic": "ExtendedPictographic",
}


def parse_ranges(path, property_map):
    """Parses UCD-format `codepoint[..codepoint] ; PropertyName # comment`
    lines, keeping only properties present in `property_map`. Returns a
    list of (start, end, enumerator_name) triples."""
    ranges = []
    with open(path, encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.split("#", 1)[0].strip()
            if not line or ";" not in line:
                continue
            cp_field, prop_field = line.split(";", 1)
            prop_name = prop_field.strip()
            if prop_name not in property_map:
                continue
            cp_field = cp_field.strip()
            if ".." in cp_field:
                start_str, end_str = cp_field.split("..")
            else:
                start_str = end_str = cp_field
            ranges.append((int(start_str, 16), int(end_str, 16), property_map[prop_name]))
    return ranges


def merge_ranges(ranges):
    """Sorts by start codepoint and merges adjacent/overlapping ranges that
    share the same property into a minimal non-overlapping list."""
    ranges = sorted(ranges)
    merged = []
    for start, end, prop in ranges:
        if merged:
            prev_start, prev_end, prev_prop = merged[-1]
            if prop == prev_prop and start <= prev_end + 1:
                merged[-1] = (prev_start, max(prev_end, end), prop)
                continue
            if start <= prev_end:
                raise ValueError(
                    f"overlapping ranges with different properties: "
                    f"({prev_start:#x}, {prev_end:#x}, {prev_prop}) vs "
                    f"({start:#x}, {end:#x}, {prop})"
                )
        merged.append((start, end, prop))
    return merged


def emit_cpp(merged, unicode_version, source_files, out_path):
    lines = []
    lines.append("// Generated by tools/unicode_data_gen/generate_grapheme_table.py")
    lines.append("// — do not edit by hand; re-run the generator to regenerate.")
    lines.append(f"// Source: Unicode {unicode_version} ({', '.join(source_files)}).")
    lines.append("")
    lines.append('#include "grapheme.h"')
    lines.append("")
    lines.append("namespace vse {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("struct GraphemeBreakRange {")
    lines.append("    u32 start;")
    lines.append("    u32 end;")
    lines.append("    GraphemeBreakProperty property;")
    lines.append("};")
    lines.append("")
    lines.append("constexpr GraphemeBreakRange kGraphemeBreakTable[] = {")
    for start, end, prop in merged:
        lines.append(f"    {{0x{start:X}, 0x{end:X}, GraphemeBreakProperty::{prop}}},")
    lines.append("};")
    lines.append("")
    lines.append(
        "constexpr usize kGraphemeBreakTableSize = "
        "sizeof(kGraphemeBreakTable) / sizeof(kGraphemeBreakTable[0]);"
    )
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("GraphemeBreakProperty LookupGraphemeBreakProperty(u32 codepoint) {")
    lines.append("    usize lo = 0;")
    lines.append("    usize hi = kGraphemeBreakTableSize;")
    lines.append("    while (lo < hi) {")
    lines.append("        usize mid = lo + (hi - lo) / 2;")
    lines.append("        const GraphemeBreakRange& range = kGraphemeBreakTable[mid];")
    lines.append("        if (codepoint < range.start) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (codepoint > range.end) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            return range.property;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return GraphemeBreakProperty::Other;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace vse")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main(argv):
    if len(argv) != 5:
        sys.exit(f"usage: {argv[0]} <GraphemeBreakProperty.txt> <emoji-data.txt> <unicode-version> <output.cpp>")
    gbp_path, emoji_path, unicode_version, out_path = argv[1:]

    ranges = parse_ranges(gbp_path, GCB_PROPERTY_MAP)
    ranges += parse_ranges(emoji_path, EMOJI_PROPERTY_MAP)
    merged = merge_ranges(ranges)

    emit_cpp(merged, unicode_version, ["GraphemeBreakProperty.txt", "emoji-data.txt"], out_path)
    print(f"Wrote {len(merged)} ranges to {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
