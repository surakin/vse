#!/usr/bin/env python3
"""Generates the three normalization data tables under
engine/foundation/string/generated/ from a pinned Unicode version's
UnicodeData.txt and CompositionExclusions.txt:

  - decomposition_table.cpp: canonical decompositions (field 5 of
    UnicodeData.txt, skipping <tag>-marked compatibility decompositions)
    plus their inverse (a composition lookup table), both binary-searched.
    Hangul syllables are deliberately excluded — normalize.cpp handles
    them via the algorithmic Hangul formula instead (see
    plans/phase-00-foundation/day-12-normalization.md).
  - combining_class_table.cpp: non-zero canonical combining classes
    (field 3), binary-searched; codepoints absent from the table default
    to combining class 0.
  - composition_exclusions_table.cpp: CompositionExclusions.txt as a
    sorted binary-searchable membership table.

Dev-time only tool (never linked or shipped in the engine/game binary —
same category as CMake itself, PLAN.md assumption #8). The generated
output is checked into the repo, not regenerated at build time.

Usage:
    python3 generate_normalization_tables.py \\
        <UnicodeData.txt> <CompositionExclusions.txt> \\
        <unicode-version> <output-dir>
"""

import sys

HANGUL_S_BASE = 0xAC00
HANGUL_S_COUNT = 19 * 21 * 28  # LCount * VCount * TCount


def parse_unicode_data(path):
    """Returns (decompositions, combining_classes):
    decompositions: list of (codepoint, [decomposed codepoints]) for
        canonical (untagged) decompositions only.
    combining_classes: list of (codepoint, class) for non-zero classes.
    """
    decompositions = []
    combining_classes = []
    with open(path, encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.rstrip("\n")
            if not line:
                continue
            fields = line.split(";")
            cp = int(fields[0], 16)
            cc = int(fields[3])
            if cc != 0:
                combining_classes.append((cp, cc))
            decomp_field = fields[5]
            if decomp_field and not decomp_field.startswith("<"):
                decomposed = [int(x, 16) for x in decomp_field.split()]
                decompositions.append((cp, decomposed))

    # Defensive: Hangul syllables are handled algorithmically in
    # normalize.cpp, never via this table (UnicodeData.txt doesn't
    # actually list per-syllable decompositions for the block, only
    # <Hangul Syllable, First>/<Hangul Syllable, Last> range markers with
    # no decomposition field — this filter just makes the exclusion
    # explicit rather than relying on that incidentally being true).
    decompositions = [
        (cp, d) for cp, d in decompositions if not (HANGUL_S_BASE <= cp < HANGUL_S_BASE + HANGUL_S_COUNT)
    ]
    return sorted(decompositions), sorted(combining_classes)


def parse_composition_exclusions(path):
    exclusions = []
    with open(path, encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.split("#", 1)[0].strip()
            if not line:
                continue
            exclusions.append(int(line, 16))
    return sorted(set(exclusions))


def emit_decomposition_table(decompositions, unicode_version, out_path):
    composition_pairs = sorted(
        ((d[0], d[1], cp) for cp, d in decompositions if len(d) == 2),
    )

    lines = []
    lines.append("// Generated by tools/unicode_data_gen/generate_normalization_tables.py")
    lines.append("// — do not edit by hand; re-run the generator to regenerate.")
    lines.append(f"// Source: Unicode {unicode_version} UnicodeData.txt canonical decompositions.")
    lines.append("// Hangul syllables are deliberately excluded — see normalize.cpp's algorithmic path.")
    lines.append("")
    lines.append('#include "normalize.h"')
    lines.append("")
    lines.append("namespace vse {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("struct DecompositionEntry {")
    lines.append("    u32 codepoint;")
    lines.append("    u32 decomposed[2];")
    lines.append("    u8 decomposed_length;")
    lines.append("};")
    lines.append("")
    lines.append("// Sorted by `codepoint`, for forward (decomposition) binary search.")
    lines.append("constexpr DecompositionEntry kDecompositionTable[] = {")
    for cp, d in decompositions:
        if len(d) == 1:
            lines.append(f"    {{0x{cp:X}, {{0x{d[0]:X}, 0}}, 1}},")
        else:
            lines.append(f"    {{0x{cp:X}, {{0x{d[0]:X}, 0x{d[1]:X}}}, 2}},")
    lines.append("};")
    lines.append("")
    lines.append(
        "constexpr usize kDecompositionTableSize = "
        "sizeof(kDecompositionTable) / sizeof(kDecompositionTable[0]);"
    )
    lines.append("")
    lines.append("struct CompositionEntry {")
    lines.append("    u32 first;")
    lines.append("    u32 second;")
    lines.append("    u32 composed;")
    lines.append("};")
    lines.append("")
    lines.append("// Inverse of the two-codepoint decompositions above, sorted by")
    lines.append("// (first, second), for reverse (composition) binary search. Exclusion")
    lines.append("// filtering (composition_exclusions_table.cpp) is applied by the caller,")
    lines.append("// not baked in here.")
    lines.append("constexpr CompositionEntry kCompositionTable[] = {")
    for a, b, composed in composition_pairs:
        lines.append(f"    {{0x{a:X}, 0x{b:X}, 0x{composed:X}}},")
    lines.append("};")
    lines.append("")
    lines.append(
        "constexpr usize kCompositionTableSize = "
        "sizeof(kCompositionTable) / sizeof(kCompositionTable[0]);"
    )
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("bool LookupCanonicalDecomposition(u32 codepoint, u32 out_decomposed[2], u8* out_length) {")
    lines.append("    usize lo = 0;")
    lines.append("    usize hi = kDecompositionTableSize;")
    lines.append("    while (lo < hi) {")
    lines.append("        usize mid = lo + (hi - lo) / 2;")
    lines.append("        const DecompositionEntry& entry = kDecompositionTable[mid];")
    lines.append("        if (codepoint < entry.codepoint) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (codepoint > entry.codepoint) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            out_decomposed[0] = entry.decomposed[0];")
    lines.append("            out_decomposed[1] = entry.decomposed[1];")
    lines.append("            *out_length = entry.decomposed_length;")
    lines.append("            return true;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return false;")
    lines.append("}")
    lines.append("")
    lines.append("bool LookupCanonicalComposition(u32 first, u32 second, u32* out_composed) {")
    lines.append("    usize lo = 0;")
    lines.append("    usize hi = kCompositionTableSize;")
    lines.append("    while (lo < hi) {")
    lines.append("        usize mid = lo + (hi - lo) / 2;")
    lines.append("        const CompositionEntry& entry = kCompositionTable[mid];")
    lines.append("        if (first < entry.first || (first == entry.first && second < entry.second)) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (first > entry.first || (first == entry.first && second > entry.second)) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            *out_composed = entry.composed;")
    lines.append("            return true;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return false;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace vse")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def emit_combining_class_table(combining_classes, unicode_version, out_path):
    lines = []
    lines.append("// Generated by tools/unicode_data_gen/generate_normalization_tables.py")
    lines.append("// — do not edit by hand; re-run the generator to regenerate.")
    lines.append(f"// Source: Unicode {unicode_version} UnicodeData.txt combining classes (field 3).")
    lines.append("")
    lines.append('#include "normalize.h"')
    lines.append("")
    lines.append("namespace vse {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("struct CombiningClassEntry {")
    lines.append("    u32 codepoint;")
    lines.append("    u8 combining_class;")
    lines.append("};")
    lines.append("")
    lines.append("constexpr CombiningClassEntry kCombiningClassTable[] = {")
    for cp, cc in combining_classes:
        lines.append(f"    {{0x{cp:X}, {cc}}},")
    lines.append("};")
    lines.append("")
    lines.append(
        "constexpr usize kCombiningClassTableSize = "
        "sizeof(kCombiningClassTable) / sizeof(kCombiningClassTable[0]);"
    )
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("u8 CombiningClass(u32 codepoint) {")
    lines.append("    usize lo = 0;")
    lines.append("    usize hi = kCombiningClassTableSize;")
    lines.append("    while (lo < hi) {")
    lines.append("        usize mid = lo + (hi - lo) / 2;")
    lines.append("        const CombiningClassEntry& entry = kCombiningClassTable[mid];")
    lines.append("        if (codepoint < entry.codepoint) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (codepoint > entry.codepoint) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            return entry.combining_class;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace vse")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def emit_composition_exclusions_table(exclusions, unicode_version, out_path):
    lines = []
    lines.append("// Generated by tools/unicode_data_gen/generate_normalization_tables.py")
    lines.append("// — do not edit by hand; re-run the generator to regenerate.")
    lines.append(f"// Source: Unicode {unicode_version} CompositionExclusions.txt.")
    lines.append("")
    lines.append('#include "normalize.h"')
    lines.append("")
    lines.append("namespace vse {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    lines.append("constexpr u32 kCompositionExclusions[] = {")
    for cp in exclusions:
        lines.append(f"    0x{cp:X},")
    lines.append("};")
    lines.append("")
    lines.append(
        "constexpr usize kCompositionExclusionsSize = "
        "sizeof(kCompositionExclusions) / sizeof(kCompositionExclusions[0]);"
    )
    lines.append("")
    lines.append("} // namespace")
    lines.append("")
    lines.append("bool IsCompositionExcluded(u32 codepoint) {")
    lines.append("    usize lo = 0;")
    lines.append("    usize hi = kCompositionExclusionsSize;")
    lines.append("    while (lo < hi) {")
    lines.append("        usize mid = lo + (hi - lo) / 2;")
    lines.append("        if (codepoint < kCompositionExclusions[mid]) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (codepoint > kCompositionExclusions[mid]) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            return true;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return false;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace vse")
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main(argv):
    if len(argv) != 5:
        sys.exit(f"usage: {argv[0]} <UnicodeData.txt> <CompositionExclusions.txt> <unicode-version> <output-dir>")
    unicode_data_path, exclusions_path, unicode_version, out_dir = argv[1:]

    decompositions, combining_classes = parse_unicode_data(unicode_data_path)
    exclusions = parse_composition_exclusions(exclusions_path)

    emit_decomposition_table(decompositions, unicode_version, f"{out_dir}/decomposition_table.cpp")
    emit_combining_class_table(combining_classes, unicode_version, f"{out_dir}/combining_class_table.cpp")
    emit_composition_exclusions_table(exclusions, unicode_version, f"{out_dir}/composition_exclusions_table.cpp")

    print(
        f"Wrote {len(decompositions)} decompositions, {len(combining_classes)} combining classes, "
        f"{len(exclusions)} composition exclusions to {out_dir}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main(sys.argv)
