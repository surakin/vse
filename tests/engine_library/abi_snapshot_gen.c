#define STRUCT(type) printf("struct " #type " size=%zu\n", sizeof(type))
#define FIELD(type, member)                                                                                            \
    do                                                                                                                 \
    {                                                                                                                  \
        const type* probe_ = NULL;                                                                                     \
        printf("field " #type "." #member " offset=%zu size=%zu\n", offsetof(type, member), sizeof(probe_->member));   \
    } while (0)

