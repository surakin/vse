u64 BtFnv(const byte* data, usize size)
{
    u64 h = 0xcbf29ce484222325ull;
    for (usize i = 0; i < size; ++i)
    {
        h = (h ^ data[i]) * 0x100000001b3ull;
    }
    return h;
}

Vector<byte> BtPhoto(u32 w, u32 h)
{
    // Smooth content: a few triangle waves per channel plus a little noise, correlated across channels.
    test::Rng rng(77);
    Vector<byte> img = BtImage(w, h);
    for (u32 y = 0; y < h; ++y)
    {
        for (u32 x = 0; x < w; ++x)
        {
            const i32 tx = static_cast<i32>((x * 5) % 128) - 64;
            const i32 ty = static_cast<i32>((y * 3) % 96) - 48;
            const i32 base = 128 + (tx < 0 ? -tx : tx) + (ty < 0 ? -ty : ty) - 60;
            const i32 n = static_cast<i32>(rng.Below(5)) - 2;
            BtSet(&img, w, x, y, static_cast<u32>((base + n + 255) % 256),
                  static_cast<u32>((base * 3 / 4 + n + 40) % 256), static_cast<u32>((255 - base / 2 + n) % 256));
        }
    }
    return img;
}

