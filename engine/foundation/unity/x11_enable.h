// Opens a region in which X11 headers may be included inside a unity build. Pair with unity/x11_disable.h at the
// end of the file.
//
// <X11/X.h> and <X11/Xlib.h> define object-like macros (`None`, `Success`, `Bool`, `Status`, `KeyPress`, ...) that
// break ordinary C++ enumerators and identifiers. With a unity build the translation unit holds several .cpp files,
// so a macro defined here would leak into the files merged after this one. This header remembers the (undefined)
// state of each such name; x11_disable.h restores it. Intentionally has no include guard.
